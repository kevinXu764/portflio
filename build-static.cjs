/* Build only: the delivered HTML and assets need no Node.js or HTTP server. */
const fs = require('fs');
const path = require('path');

let esbuild;
try {
  // An explicit package path lets maintainers reuse an existing local toolchain.
  esbuild = require(process.argv[2] ? path.resolve(process.argv[2]) : 'esbuild');
} catch (error) {
  console.error('Build tool missing. Run npm install --cache .build-cache, then npm run build.');
  console.error('Or: node build-static.cjs <path-to-an-existing-esbuild-package>');
  process.exit(1);
}

const root = __dirname;
for (const [entry, output] of [
  ['app.js', 'app.bundle.js'],
]) {
  esbuild.buildSync({
    absWorkingDir: root,
    entryPoints: [entry],
    outfile: path.join(root, 'assets', output),
    bundle: true,
    splitting: false,
    format: 'iife',
    platform: 'browser',
    target: ['es2020'],
    minify: true,
    charset: 'utf8',
    legalComments: 'inline',
    banner: {js: '/* Generated by build-static.cjs. Edit source files, then rebuild. Three.js: ../vendor/THREE-LICENSE.txt */'},
    logLevel: 'warning',
  });
  const size = fs.statSync(path.join(root, 'assets', output)).size;
  console.log(`Built assets/${output} (${Math.round(size / 1024)} KiB)`);
}
console.log('Ready: open index.html directly, or double-click the Windows launcher.');
